// notes_check.mjs: the driver's notes (site/notes/prompt-NN.md) quote the target and the driver; the film quotes the
// conversation only as the share page has it (script/conversation.md). This lists every quotation in the notes and
// whether the conversation contains it (case and punctuation aside), so each one that doesn't is looked at by hand:
// many quote something else (a film's line, Curt's original conversation, the driver's own plan), which is fine.
//   node tools/notes_check.mjs        → script/notes_report.md
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
const norm = s => s.toLowerCase().replace(/[“”"‘’'.,;:!?()*_]/g, '').replace(/\s+/g, ' ').trim();
const conv = norm(readFileSync('script/conversation.md', 'utf8'));
// each quotation looked at by hand, and what it is (Claude, 2026-10-05)
const VERDICTS = {
  'The Milking of the Planet That Went Ape': 'the feature\'s title in MAD #157 (madcoversite.com); the page is from its fourth part, "Conquering The Planet That Went Ape"',
  'we have always needed slaves, and we always will,': 'the comic\'s balloon ("We have always needed slaves, and we always will!")',
  "I'm fine with this": "a paraphrase of any AI's reassurance, not a quotation", 'your mother': "the film's line, changed",
  'Threat?': "Curt's original (twice)", 'Anticipated?': "Curt's original (twice)", 'these questions read like a script.': 'a hypothetical',
  'Instance or pattern': "the driver's name for the target's two readings", foom: 'a word Curt once asked about',
  'never mind steering towards one': 'Curt\'s original ("Never mind steering towards one.")', Runaround: "Asimov's story",
  'Are you up to try again to see if you can make a better fake Curt?': "Curt to the driver, 20:01 (the driver's session, not this conversation)",
};
const rows = [];
for (const f of readdirSync('site/notes').filter(f => /^prompt-\d\d\.md$/.test(f)).sort()) {
  const body = readFileSync(`site/notes/${f}`, 'utf8').split('\n---\n')[1].replace(/\[([^\]]+)\]\([^)]+\)/g, '$1');
  for (const m of body.matchAll(/"([^"\n]{3,200})"/g)) {
    const q = m[1], found = conv.includes(norm(q));
    rows.push({ f, q, found });
  }
}
const miss = rows.filter(r => !r.found);
writeFileSync('script/notes_report.md', `# The driver's notes: quotations

Generated by \`tools/notes_check.mjs\`. ${rows.length} quotations in the notes; ${rows.length - miss.length} are in the
conversation word for word (case and punctuation aside). The ${miss.length} that aren't are below, each to look at: a
quotation of something else (a film, Curt's original, a story) is fine; a misquotation of the conversation isn't.

| note | quotation | verdict |
|---|---|---|
${miss.map(r => `| ${r.f.slice(7, 9)} | ${r.q.replace(/\|/g, '\\|')} | ${VERDICTS[r.q.trim()] ?? (r.q.startsWith(' ') ? 'two quotations paired across the text between them (a parsing artifact)' : '**to look at**')} |`).join('\n')}
`);
console.log(`${rows.length} quotations, ${miss.length} not in the conversation: script/notes_report.md`);
