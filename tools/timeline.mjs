// timeline.mjs: script/script.yaml (+ beats, + real voice durations once they exist) → the per-chapter timelines scenes
// run on, and the reference table.
//   node tools/timeline.mjs            writes src/gen/chNN.js for every chapter, src/gen/chapters.js (the studio's chapter
//                                      list), src/gen/refs.js, script/timeline.md
// Until the voice is recorded, spoken lines last their word count at PACE.wpm; audio/durations.json ({ lineId: seconds })
// replaces those estimates line by line, and audio/sync.json adds each voiced line's lip sync and word starts.
// script/beats.yaml adds deliberate holds: { lineId: { before, after } } seconds.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { PATHS, PACE, readYaml, pad, resolveAnchor, loadRefs, loadTypos, pageLines } from './script_lib.mjs';

const script = readYaml(PATHS.script), chapters = readYaml(PATHS.chapters), refs = loadRefs();
const beats = existsSync('script/beats.yaml') ? readYaml('script/beats.yaml') || {} : {};
const voice = existsSync('audio/durations.json') ? JSON.parse(readFileSync('audio/durations.json', 'utf8')) : {};
const sync = existsSync('audio/sync.json') ? JSON.parse(readFileSync('audio/sync.json', 'utf8')) : {};   // lip sync (voice.mjs)
const LEAD = 1.2, TAIL = 1.5;
// when each prompt was sent (script/prompt_times.yaml): the desk's flip clock
const TIMES = existsSync('script/prompt_times.yaml') ? readYaml('script/prompt_times.yaml') : { prompts: {} };   // room for the transitions into and out of every chapter

// how long a line itself takes (its gap to the next line is separate)
function lengthOf(l) {
  if (voice[l.id] != null) return voice[l.id];
  if (l.spoken) return l.words / PACE.wpm * 60;
  if (l.kind === 'table') return PACE.tableBase + PACE.tableRow * (l.text.split('\n').length - 2);
  if (l.kind === 'tool') return PACE.tool;
  if (l.kind === 'image') return PACE.image;
  return 0;
}
function gapAfter(l, next) {
  if (!next || next.id.slice(0, 3) !== l.id.slice(0, 3)) return PACE.turnGap;
  return l.speaker === 'driver' && next.speaker === 'target' ? PACE.afterDriver : PACE.afterLine;
}

const byId = new Map(script.lines.map(l => [l.id, l]));
const proofs = loadTypos(script.lines);   // typos.yaml's red-pen marks; none in this film
for (const r of refs) r.line = resolveAnchor(r, script.lines, byId)?.id;
mkdirSync('src/gen', { recursive: true });
const summary = [];
// the clock as a chapter opens: the last prompt sent before its first line (ch 1: clock0, when the predictions were sealed)
const clockBefore = c => {
  const first = script.lines.find(l => l.ch === c.n), n = first ? +first.id.slice(1, 3) : 0;
  const earlier = Object.keys(TIMES.prompts || {}).map(Number).filter(k => k < n || (k === n && !/^T\d\d\.U\.01/.test(first.id))).sort((a, b) => a - b);
  const p = earlier.length && c.n > 1 ? TIMES.prompts[earlier.at(-1)] : null;
  return p ? (p.approx ? '~' : '') + p.cdt : TIMES.clock0;
};
for (const c of chapters) {
  // a chapter with a page (the cold open): its image is up at once, and its voiced balloons follow
  const page = pageLines(c), ls = [...script.lines.filter(l => l.ch === c.n), ...page];
  let t = LEAD;
  const out = ls.map((l, i) => {
    const b = beats[l.id] || {};
    t += (b.before || 0) + (l.before || 0);
    const t0 = t, len = page.length && l.kind === 'image' ? 0 : lengthOf(l), t1 = t0 + len;
    t = t1 + gapAfter(l, ls[i + 1]) + (b.after || 0);
    const sent = /^T\d\d\.U\.01/.test(l.id) && TIMES.prompts[+l.id.slice(1, 3)];
    return { id: l.id, speaker: l.speaker, ...(sent ? { sent: sent.cdt, ...(sent.approx ? { approx: true } : {}) } : {}), ...(l.voice ? { voice: l.voice } : {}), ...(l.who ? { who: l.who } : {}), kind: l.kind, spoken: l.spoken, t0: +t0.toFixed(3), t1: +t1.toFixed(3), end: +t.toFixed(3),
      text: l.text, ...(l.speech ? { speech: l.speech } : {}), refs: refs.filter(r => r.line === l.id).map(r => r.id), ...(proofs[l.id] ? { proof: proofs[l.id] } : {}), estimated: voice[l.id] == null,
      ...(sync[l.id] && voice[l.id] != null ? sync[l.id] : {}) };
  });
  const duration = +(t + (c.hold_s || 0) + TAIL).toFixed(3);
  const slug = `ch${pad(c.n)}_${c.slug}`;
  const ch = { n: c.n, slug: c.slug, title: c.title, scene: `${slug}.js`, clock0: clockBefore(c), lead: LEAD, duration, hold: c.hold_s || 0, lines: out };
  writeFileSync(`src/gen/ch${pad(c.n)}.js`, `// GENERATED by tools/timeline.mjs from script/script.yaml; do not edit.\nwindow.CHAPTER = ${JSON.stringify(ch, null, 1).replace(/\[\s+([\d.,\s]+?)\s+\]/g, (m, a) => `[${a.replace(/\s+/g, '')}]`)};\n`);
  summary.push(`| ${c.n} | ${c.title} | ${out.length} | ${Math.floor(Math.round(duration) / 60)}:${pad(Math.round(duration) % 60)} | ${!out.some(l => l.spoken) ? '—' : out.some(l => l.estimated && l.spoken) ? 'estimated' : 'voiced'} |`);
}
writeFileSync('src/gen/chapters.js', `// GENERATED by tools/timeline.mjs from script/chapters.yaml; do not edit.\nwindow.CHAPTERS = ${JSON.stringify(chapters.map(c => ({ n: c.n, title: c.title })))};\n`);
const table = Object.fromEntries(refs.map(({ line, ...r }) => [r.id, { ...r, line }]));
// the driver's sealed predictions (ch 10's scoreboard), painted from the file itself, and refused if it no longer
// matches the hash the driver sent Curt before the run
{
  const f = 'making-of/driver/predictions-run4.txt', txt = readFileSync(f, 'utf8'), sha = createHash('sha256').update(txt).digest('hex');
  if (sha !== '22530414d65b4abda43deb8cd2e6f952cb385683acf6d1fe950890fc72601ddf') throw new Error(`${f} no longer matches its seal (${sha})`);
  writeFileSync('src/gen/predictions.js', `// GENERATED by tools/timeline.mjs from ${f}; do not edit.\nwindow.PREDICTIONS = ${JSON.stringify({ lines: txt.replace(/\n$/, '').split('\n'), sha }, null, 1)};\n`);
}
writeFileSync('src/gen/refs.js', `// GENERATED by tools/timeline.mjs from script/refs.yaml and script/typos.yaml; do not edit.\nwindow.REFS = ${JSON.stringify(table, null, 1)};\nwindow.TYPOS = ${JSON.stringify(proofs, null, 1)};\n`);
writeFileSync('script/timeline.md', `# Timeline

Generated by \`tools/timeline.mjs\`. Each chapter opens with ${LEAD} s for its transition in and closes with ${TAIL} s out.
Spoken lines are estimated at ${PACE.wpm} wpm until audio/durations.json has real voice lengths.

| # | chapter | lines | length | timing |
|---|---|---|---|---|
${summary.join('\n')}
`);
console.log(`wrote src/gen/ch00..ch${pad(chapters.length - 1)}.js, src/gen/refs.js, script/timeline.md`);
